package com.millsystem.controller;

import com.millsystem.dto.GpsPingDto;
import com.millsystem.entity.Mill;
import com.millsystem.service.GpsDeviceKeyService;
import com.millsystem.service.TruckTrackingService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.Map;
import java.util.Optional;

@RestController
@RequestMapping("/api/gps")
@Tag(name = "GPS Device Ingest", description = "For GPS devices on trucks. Authenticate with the mill's device key in the X-Device-Key header (generated by the mill admin on the Truck Tracking screen).")
public class GpsController {

    private final TruckTrackingService truckService;
    private final GpsDeviceKeyService deviceKeys;

    public GpsController(TruckTrackingService truckService, GpsDeviceKeyService deviceKeys) {
        this.truckService = truckService;
        this.deviceKeys = deviceKeys;
    }

    @PostMapping("/ping")
    @Operation(summary = "Report truck location",
            description = "Header X-Device-Key: the mill's GPS device key. Body: truckNumber, latitude (-90..90), longitude (-180..180), optional speed (km/h) and recordedAt (defaults to now).")
    public ResponseEntity<Map<String, String>> ping(@RequestHeader(value = "X-Device-Key", required = false) String deviceKey,
                                                    @Valid @RequestBody GpsPingDto dto) {
        Optional<Mill> mill = deviceKeys.millFor(deviceKey);
        if (mill.isEmpty()) {
            return ResponseEntity.status(HttpStatus.UNAUTHORIZED).body(Map.of("error", "Missing or invalid device key"));
        }
        deviceKeys.checkRate(mill.get().getId());
        truckService.recordPing(mill.get(), dto);
        return ResponseEntity.status(HttpStatus.CREATED)
                .body(Map.of("message", "Location recorded for truck " + dto.getTruckNumber().trim().toUpperCase()));
    }
}
